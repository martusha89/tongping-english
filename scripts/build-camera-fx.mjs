// Builds the card's camera effects from the user's standalone demo
// (docs/camera_face_effects_astra_v10.html) without hand-copying it:
//   assets/camera-fx/geometry.js  – the demo's FaceGeometry script, verbatim
//   assets/camera-fx/engine.js    – the demo's renderers/detector, verbatim,
//                                   wrapped in a small API for the card
// The demo's own page wiring (buttons, photo sheet) is left out; the card
// drives the engine through window.TongpingCameraFx instead.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const demo = fs.readFileSync(path.join(root, "docs/camera_face_effects_astra_v10.html"), "utf8");

function scriptBody(id) {
  const open = `<script id="${id}">`;
  const start = demo.indexOf(open);
  if (start < 0) throw new Error("demo script #" + id + " not found");
  return demo.slice(start + open.length, demo.indexOf("</script>", start));
}

function between(source, from, to) {
  const start = source.indexOf(from);
  const end = source.indexOf(to, start);
  if (start < 0 || end < 0) throw new Error("demo slice not found: " + from + " … " + to);
  return source.slice(start, end);
}

const geometry = scriptBody("geometry");
const app = scriptBody("app");
const constants = between(app, "const CDN=", "\n");
// Lip makeup, retuned for the card (2026-10-03): the demo
// fills the lips once inside a hard clip, which reads as a glossy sticker.
// Here the same lip shape is painted five times, from slightly larger to
// slightly smaller, at low alpha, so the edge and corners fade out, in a
// muted rose / nude pink instead of saturated red.
const LIP_DEMO = "ctx.save();ctx.beginPath();path(G.mouth);path(G.innerMouth);ctx.clip('evenodd');const up=pt(0),dn=pt(17),g=ctx.createLinearGradient(0,up[1],0,dn[1]);g.addColorStop(0,'rgba(172,62, seventy,.25)'.replace('seventy','70'));g.addColorStop(.5,'rgba(181, sixty,80,.32)'.replace('sixty','60'));g.addColorStop(1,'rgba(230,134,137,.20)');ctx.fillStyle=g;ctx.fillRect(-1,-1,2,3);ctx.restore();";
const LIP_SOFT = "{const mp=G.mouth.map(pt),mc=[mp.reduce((v,p)=>v+p[0],0)/mp.length,mp.reduce((v,p)=>v+p[1],0)/mp.length],up=pt(0),dn=pt(17),ga=ctx.globalAlpha;" +
  "const lipPath=k=>{ctx.beginPath();for(const ids of [G.mouth,G.innerMouth]){const p=ids.map(pt).map(q=>[mc[0]+(q[0]-mc[0])*k,mc[1]+(q[1]-mc[1])*k]);ctx.moveTo(...p[0]);for(let i=1;i<p.length;i++)ctx.lineTo(...p[i]);ctx.closePath();}};" +
  "for(const [k,a] of [[1.08,.14],[1.04,.2],[1,.26],[.95,.3],[.9,.34]]){ctx.save();lipPath(k);ctx.clip('evenodd');const g=ctx.createLinearGradient(0,up[1],0,dn[1]);" +
  "g.addColorStop(0,'rgba(170,104,106,.30)');g.addColorStop(.5,'rgba(186,116,116,.34)');g.addColorStop(1,'rgba(212,152,148,.22)');" +
  "ctx.globalAlpha=ga*a;ctx.fillStyle=g;ctx.fillRect(-1,-1,2,3);ctx.restore();}ctx.globalAlpha=ga;}";
const renderersDemo = between(app, "class Renderer{", "function stop(){");
if (!renderersDemo.includes(LIP_DEMO)) throw new Error("demo lip makeup changed; update LIP_DEMO");
const renderers = renderersDemo.replace(LIP_DEMO, LIP_SOFT);
const quality = between(app, "function quality(", "async function tick(");

const prelude = `/* Generated by scripts/build-camera-fx.mjs from docs/camera_face_effects_astra_v10.html. Do not edit. */
(()=>{'use strict';
const G=window.FaceGeometry;
${constants}
let engine=null,enginePromise=null,lastMetrics=null,makeup=false;const stickers=new Set();
const frame=document.createElement('canvas'),fg=frame.getContext('2d',{alpha:false});
let onStatus=()=>{};const report=s=>{try{onStatus(s);}catch(_){}};
`;

const api = `
// ----- card API -----
// Every look except Original sits on the Beauty base (smoothing + light makeup).
const LOOKS={
 none:{mode:'none',beauty:false,decor:true,makeup:false,stickers:[]},
 soft:{mode:'none',beauty:true,decor:true,makeup:true,stickers:[]},
 cat:{mode:'cat',beauty:true,decor:true,makeup:true,stickers:[]},
 bunny:{mode:'cat',beauty:true,decor:false,makeup:true,stickers:['bunny','whiskers']},
 bird:{mode:'bird',beauty:true,decor:true,makeup:true,stickers:[]},
 frog:{mode:'frog',beauty:true,decor:true,makeup:true,stickers:[]},
 hearts:{mode:'none',beauty:true,decor:true,makeup:true,stickers:['hearts']},
 stars:{mode:'none',beauty:true,decor:true,makeup:true,stickers:['stars']}
};
let video=null,canvas=null,renderer=null,stream=null,running=false,generation=0,raf=0,lastTick=0,lastTime=-1;
let mode='none',beauty=false,decor=true,intensity=.8,facing='user',tracked=false,effectsReady=false;
function setLook(name){const l=LOOKS[name]||LOOKS.none;mode=l.mode;beauty=l.beauty;decor=l.decor;makeup=l.makeup;stickers.clear();for(const s of l.stickers)stickers.add(s);}
function drawPlain(){const ratio=Math.min(1,720/Math.max(video.videoWidth,video.videoHeight)),w=Math.round(video.videoWidth*ratio),h=Math.round(video.videoHeight*ratio);if(!w||!h)return false;if(frame.width!==w||frame.height!==h){frame.width=w;frame.height=h;lastMetrics=null;}fg.drawImage(video,0,0,w,h);return true;}
async function tick(t){
 if(!running)return;const gen=generation;
 if(document.hidden||t-lastTick<1000/24||video.currentTime===lastTime){raf=requestAnimationFrame(tick);return;}
 lastTick=t;lastTime=video.currentTime;
 try{
  if(!drawPlain()){raf=requestAnimationFrame(tick);return;}
  let lm=null;if(engine&&effectsReady){try{lm=await engine.detect(frame,t);}catch(e){effectsReady=false;report('Effects paused: '+e.message+' · using original view for now');}}
  if(gen!==generation||!running)return;
  const q=lm?quality(lm,t):0;tracked=!!lm;
  renderer.draw(frame,q>0?lm:null,mode,intensity*q,beauty&&q>.35,facing==='user',decor);
 }catch(e){if(gen===generation)report('Video error: '+e.message);}
 if(gen===generation&&running)raf=requestAnimationFrame(tick);
}
function close(){generation++;running=false;cancelAnimationFrame(raf);if(stream)stream.getTracks().forEach(t=>t.stop());stream=null;if(video)video.srcObject=null;lastTime=-1;lastMetrics=null;tracked=false;}
async function open(opts){
 close();const gen=generation;video=opts.video;canvas=opts.canvas;onStatus=opts.onStatus||(()=>{});
 if(!navigator.mediaDevices||!navigator.mediaDevices.getUserMedia)throw Object.assign(Error('Camera is unavailable here'),{name:'NotSupportedError'});
 const incoming=await navigator.mediaDevices.getUserMedia({audio:false,video:{facingMode:{ideal:facing},width:{ideal:640},height:{ideal:854},frameRate:{ideal:24,max:30}}});
 if(gen!==generation){incoming.getTracks().forEach(t=>t.stop());return false;}
 stream=incoming;video.srcObject=stream;video.muted=true;video.playsInline=true;await video.play();
 if(!renderer||renderer.canvas!==canvas)renderer=new SceneRenderer(canvas);
 running=true;raf=requestAnimationFrame(tick);
 report('Camera on · loading effects…');
 loadEngine().then(()=>{if(gen!==generation)return;effectsReady=true;report('');}).catch(e=>{if(gen!==generation)return;effectsReady=false;report('Effects failed to load; using original view for now ('+e.message+')');});
 return true;
}
async function flip(){facing=facing==='user'?'environment':'user';if(stream&&video&&canvas)return open({video,canvas,onStatus});}
window.TongpingCameraFx={open,close,flip,setLook,looks:Object.keys(LOOKS),isOpen:()=>!!stream,faceTracked:()=>tracked,effectsReady:()=>effectsReady,
 setIntensity:v=>{intensity=Math.max(0,Math.min(1,Number(v)||0));}};
})();
`;

const outDir = path.join(root, "assets/camera-fx");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "geometry.js"), "/* Generated from docs/camera_face_effects_astra_v10.html. Do not edit. */\n" + geometry.trim() + "\n");
fs.writeFileSync(path.join(outDir, "engine.js"), prelude + renderers + "\n" + quality + api);
console.log("camera-fx built:", fs.statSync(path.join(outDir, "geometry.js")).size, fs.statSync(path.join(outDir, "engine.js")).size);
